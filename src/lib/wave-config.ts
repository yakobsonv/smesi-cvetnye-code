/** Параметры объёмной волны образцов на первом экране главной (сцена — src/lib/mortar-wave.ts,
 *  статичная CSS-раскладка — src/components/smesi/MortarWave.astro). Отдельный файл без three:
 *  его читает и сборка страницы (раскладка без WebGL), и сцена. Менять волну — здесь. */
/** Все параметры волны — в одном месте. Единицы сцены условные: высота пластины ≈ 1,1. */
export const WAVE_CONFIG = {
  /** количество пластин (бриф: 24–32); 8 оттенков палитры идут блоками по count / 8 пластин */
  count: 32,
  /** шаг между пластинами вдоль кривой */
  spacing: 0.17,
  /** пластина: ширина (вглубь), высота, толщина и радиус скругления кромки */
  plate: { width: 0.74, height: 1.06, thickness: 0.05, radius: 0.016 },
  /** базовый разворот пластин к зрителю вокруг вертикали, рад — чтобы были видны лицевые стороны */
  yaw: 0.68,
  /** форма неподвижной кривой: перепад высоты, прогиб к зрителю, закрутка ленты вокруг её оси —
   *  поворот крайних пластин, рад (от −twist слева до +twist справа, монотонно) */
  curve: { rise: 0.1, depth: 0.55, twist: 1.3 },
  /** бегущая волна: y = amplitude · sin(i · phaseStep − direction · t · speed); direction: −1 — гребень идёт
   *  влево (к светлым оттенкам), 1 — вправо; tilt — доля наклона от производной, roll — лёгкое покачивание
   *  вокруг оси волны (рад) */
  wave: { amplitude: 0.26, phaseStep: 0.26, speed: 0.5, direction: -1, tilt: 0.6, roll: 0.22 },
  /** сборка при старте: длительность одной пластины (с), задержка между соседними (с), разброс из сжатой стопки */
  assemble: { duration: 1.4, stagger: 0.02, scatter: 0.3 },
  /** наведение: подъём и выдвижение к зрителю, ширина затухания на соседей (в пластинах), инерция */
  hover: { lift: 0.14, push: 0.32, sigma: 1.25, ease: 9 },
  /** блок выбранного оттенка приподнят слабее, чем при наведении (доля от hover) */
  selected: 0.55,
  /** наклон всей сцены за курсором (градусы) и инерция */
  pointer: { tiltDeg: 3, ease: 3.2 },
  /** шлейф частиц при смене оттенка: круглые точки, немного */
  particles: { count: 24, lifeMin: 0.6, lifeMax: 0.9, speed: 0.75, size: 0.045 },
  /** материал раствора: шероховатость лица и торца, насколько торец темнее лица */
  material: { roughness: 0.9, edgeRoughness: 0.97, edgeShade: 0.82, bump: 1.2 },
  /** предел плотности пикселей (бриф: min(devicePixelRatio, 2)) */
  maxPixelRatio: 2,
  /** угол обзора камеры, град */
  fov: 30,
  /** кадрирование: запас по ширине на компьютере и на узком кадре (уже 1,7:1) и половина высоты кадра (единицы сцены);
   *  закрутка и разворот пластин расширяют ленту в проекции, поэтому запас больше половины ширины пластины;
   *  лента целиком в кадре на всех ширинах — видны все 8 оттенков (20.10); offsetX чуть влево —
   *  в перспективе правый край ленты шире левого */
  view: { marginX: 0.6, marginXPhone: 0.5, halfHeight: 1.05, offsetX: -0.1, offsetXPhone: -0.15 },
} as const;

/** Номер оттенка пластины: цвета идут блоками подряд, а не полосами через одну (общая формула сцены и CSS-раскладки). */
export const colorOfPlate = (i: number, n: number, p: number) => Math.floor((i * p) / n);
/** Средняя пластина блока оттенка — откуда летит шлейф. */
export const middleOfColor = (c: number, n: number, p: number) => Math.round(((c + 0.5) * n) / p - 0.5);
