import { POSITIONS, seriesById } from '../data/catalog';
import { swatchFor } from '../data/swatches';

export interface WaveColor {
  /** id позиции каталога: 'perel-sl-01' */
  id: string;
  /** название оттенка: 'супер-белый' */
  name: string;
  /** артикул / код: '0001', '071' */
  article: string;
  /** серия: 'Perel SL' */
  series: string;
  /** полное название позиции — для окна «Узнать цену» (data-ask) */
  title: string;
  /** HEX плашки (приближение) */
  hex: string;
  /** швы кадра кладки по близости тона, см. таблицу выше */
  seams: string[];
}

const PICK: Array<[positionId: string, seams: string[]]> = [
  ['perel-sl-01', ['superwhite', 'white']],
  ['perel-sl-20', ['cream', 'lightgrey', 'white']],
  ['perel-sl-40', ['cream', 'grey', 'lightbrown', 'lightgrey']],
  ['osnovit-mc11-071', ['lightbrown', 'cream', 'lightgrey']],
  ['osnovit-mc11-083', ['brown', 'lightbrown', 'darkbrown']],
  ['perel-sl-60', ['brown', 'lightbrown', 'darkbrown']],
  ['perel-sl-50', ['lightbrown', 'brown', 'darkbrown']],
  ['osnovit-mc11-023', ['darkgrey', 'blackbrown', 'black']],
];

export const WAVE_PALETTE: WaveColor[] = PICK.map(([id, seams]) => {
  const p = POSITIONS.find((x) => x.id === id);
  if (!p) throw new Error(`Нет позиции ${id} в каталоге`);
  return {
    id,
    name: p.color.name,
    article: p.article,
    series: seriesById(p.series).name,
    title: p.title,
    hex: swatchFor(p.series, p.color.code),
    seams,
  };
});
