/** Типографика для своих текстов: неразрывный пробел после коротких предлогов и союзов и между
 *  числом и единицей — чтобы в заголовках не висело «для /» в конце строки, а в таблицах не рвалось
 *  «28 / суток», «25 / кг» (сквозная проверка 11.10). Дословные цитаты производителей по смыслу
 *  не меняются: заменяются только обычные пробелы на неразрывные. */
const NB = ' ';
const SHORT = 'в|во|на|с|со|к|ко|о|об|от|до|из|у|и|а|но|по|за|для|при|без|под|над|не|ни|же';

export function nb(text: string): string {
  if (!text) return text;
  return text
    // предлог/союз + пробел → неразрывный (в начале строки и после пробела/скобки/кавычки)
    .replace(new RegExp(`(^|[\\s(«„—–-])(${SHORT}) `, 'giu'), `$1$2${NB}`)
    // число + единица/слово: «28 суток», «25 кг», «10 мм», «5–12 %»
    .replace(/(\d) (?=[%°А-Яа-яЁёA-Za-z])/gu, `$1${NB}`)
    // «+20… +40 °C»
    .replace(/… (?=[+−-]?\d)/gu, `…${NB}`);
}
